export const HAZARD_COUNT = HAZARD_ORDER.length;

export function countHazards(stories: Story[]) {
  return HAZARD_ORDER.reduce<Record<HazardKey, number>>(
    (counts, hazard) => {
      counts[hazard] = stories.filter((story) => story.hazard === hazard).length;
      return counts;
    },
    {
      flood: 0,
      cyclone: 0,
      heatwave: 0,
      earthquake: 0,
      drought: 0,
      wildfire: 0,
    },
  );
}
