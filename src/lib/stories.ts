function toHandle(name: string) {
  return `@${name.toLowerCase().replace(/[^a-z0-9]/g, "")}`;
}

function buildGeneratedStories(count: number): Story[] {
  return Array.from({ length: count }, (_, index) => {
    const hazard = HAZARD_ORDER[Math.floor(index / 45) % HAZARD_ORDER.length];
    const hazardIndex = index % 45;
    const phrases = PHRASES[hazard];
    const action = phrases.actions[hazardIndex % phrases.actions.length];
    const lesson =
      phrases.lessons[
        (hazardIndex * 3 + Math.floor(hazardIndex / phrases.actions.length)) %
          phrases.lessons.length
      ];

    const name = `${FIRST_NAMES[index % FIRST_NAMES.length]} ${
      LAST_NAMES[
        (index * 7 + Math.floor(index / FIRST_NAMES.length)) % LAST_NAMES.length
      ]
    }`;
    const likes = 180 + ((index * 977) % 5600);
    const location =
      LOCATIONS[(index * 7 + Math.floor(index / LOCATIONS.length)) % LOCATIONS.length];

    return {
      id: `gj-gen-${String(index + 1).padStart(3, "0")}`,
      name,
      handle: toHandle(name),
      role: ROLES[(index * 11) % ROLES.length],
      location,
      hazard,
      body: `${action} ${lesson}`,
      hashtag: "#GIDM",
      time: TIMES[index % TIMES.length],
      likes,
      reposts: Math.floor(likes * 0.23) + (index % 17),
      replies: 6 + ((index * 31) % 180),
      verified: index % 17 === 0,
    };
  });
}

